type vbaArrayRenderer struct{}

func (vbaArrayRenderer) Info() registry.Info {
	return registry.Info{
		Name:        "vba-array",
		Description: "Visual Basic for Applications Byte array (data declaration only)",
		Security:    registry.SecurityRenderer,
		Reversible:  true,
		Input:       "transformed bytes",
		Output:      "VBA source text",
		Parameters:  []string{"--symbol NAME", "--bytes-per-line N"},
	}
}

func (vbaArrayRenderer) Render(data []byte, meta registry.Meta) ([]byte, error) {
	symbol, err := resolveSymbol(meta, "VBA")
	if err != nil {
		return nil, err
	}
	cols, err := resolveCols(meta)
	if err != nil {
		return nil, err
	}

	var b strings.Builder
	writeLangHeader(&b, "' ", meta, data)
	if len(data) == 0 {
		fmt.Fprintf(&b, "Dim %s() As Byte ' placeholder: input was empty\n", symbol)
		return []byte(b.String()), nil
	}
	fmt.Fprintf(&b, "Dim %s(0 To %d) As Byte\n", symbol, len(data)-1)
	for i := 0; i < len(data); i += cols {
		end := i + cols
		if end > len(data) {
			end = len(data)
		}
		b.WriteString("    ")
		for j := i; j < end; j++ {
			if j > i {
				b.WriteString(": ")
			}
			fmt.Fprintf(&b, "%s(%d) = %d", symbol, j, data[j])
		}
		b.WriteString("\n")
	}
	return []byte(b.String()), nil
}

// ---------------------------------------------------------------- VBS

type vbsArrayRenderer struct{}

func (vbsArrayRenderer) Info() registry.Info {
	return registry.Info{
		Name:        "vbs-array",
		Description: "VBScript byte array (data declaration only)",
		Security:    registry.SecurityRenderer,
		Reversible:  true,
		Input:       "transformed bytes",
		Output:      "VBScript source text",
		Parameters:  []string{"--symbol NAME", "--bytes-per-line N"},
	}
}

func (vbsArrayRenderer) Render(data []byte, meta registry.Meta) ([]byte, error) {
	symbol, err := resolveSymbol(meta, "VBScript")
	if err != nil {
		return nil, err
	}
	cols, err := resolveCols(meta)
	if err != nil {
		return nil, err
	}

	var b strings.Builder
	writeLangHeader(&b, "' ", meta, data)
	if len(data) == 0 {
		fmt.Fprintf(&b, "%s = Array()\n", symbol)
		return []byte(b.String()), nil
	}

	if len(data) <= cols {
		fmt.Fprintf(&b, "%s = Array(", symbol)
		writeDecimalValues(&b, data)
		b.WriteString(")\n")
		return []byte(b.String()), nil
	}

	fmt.Fprintf(&b, "%s = Array( _\n", symbol)
	for i := 0; i < len(data); i += cols {
		end := i + cols
		if end > len(data) {
			end = len(data)
		}
		b.WriteString("    ")
		writeDecimalValues(&b, data[i:end])
		if end < len(data) {
			b.WriteString(", _\n")
		} else {
			b.WriteString(")\n")
		}
	}
	return []byte(b.String()), nil
}

func writeDecimalValues(b *strings.Builder, data []byte) {
	for i, by := range data {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "%d", by)
	}
}

