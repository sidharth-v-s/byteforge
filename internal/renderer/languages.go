// ---------------------------------------------------------------- PowerShell

type powershellBytesRenderer struct{}

func (powershellBytesRenderer) Info() registry.Info {
	return registry.Info{
		Name:        "powershell-bytes",
		Description: "PowerShell byte array (data declaration only)",
		Security:    registry.SecurityRenderer,
		Reversible:  true,
		Input:       "transformed bytes",
		Output:      "PowerShell source text",
		Parameters:  []string{"--symbol NAME (leading $ optional)", "--bytes-per-line N"},
	}
}

func (powershellBytesRenderer) Render(data []byte, meta registry.Meta) ([]byte, error) {
	raw := meta.Symbol
	if raw == "" {
		raw = "data"
	}
	raw = strings.TrimPrefix(raw, "$")
	if !symbolPattern.MatchString(raw) {
		return nil, bferrors.New(bferrors.Usage,
			"invalid PowerShell variable name %q: must match [A-Za-z_][A-Za-z0-9_]*", meta.Symbol)
	}
	cols, err := resolveCols(meta)
	if err != nil {
		return nil, err
	}
	symbol := "$" + raw

	var b strings.Builder
	writeLangHeader(&b, "# ", meta, data)
	if len(data) == 0 {
		fmt.Fprintf(&b, "[byte[]] %s = @()\n", symbol)
		return []byte(b.String()), nil
	}
	fmt.Fprintf(&b, "[byte[]] %s = @(\n", symbol)
	writeHexRows(&b, data, cols, "    ", "", false)
	b.WriteString(")\n")
	return []byte(b.String()), nil
}

