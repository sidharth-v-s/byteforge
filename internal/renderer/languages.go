// The language renderers below all emit data declarations only. None of them
// emit loaders, allocation helpers, process execution, or imports.

func writeLangHeader(b *strings.Builder, prefix string, meta registry.Meta, data []byte) {
	fmt.Fprintf(b, "%sGenerated by ByteForge %s - data declaration only.\n", prefix, version.Version)
	if meta.Operation == "" {
		return
	}
	fmt.Fprintf(b, "%sOperation: %s", prefix, meta.Operation)
	if meta.Format != "" {
		fmt.Fprintf(b, " | Format: %s", meta.Format)
	}
	sum := sha256.Sum256(data)
	fmt.Fprintf(b, " | Bytes: %d | SHA-256: %s\n", len(data), hex.EncodeToString(sum[:]))
}

func resolveSymbol(meta registry.Meta, language string) (string, error) {
	symbol := meta.Symbol
	if symbol == "" {
		symbol = "data"
	}
	if !symbolPattern.MatchString(symbol) {
		return "", bferrors.New(bferrors.Usage,
			"invalid %s symbol name %q: must match [A-Za-z_][A-Za-z0-9_]*", language, symbol)
	}
	return symbol, nil
}

func resolveCols(meta registry.Meta) (int, error) {
	cols := meta.BytesPerLine
	if cols == 0 {
		cols = 16
	}
	if cols < 1 || cols > 256 {
		return 0, bferrors.New(bferrors.Usage,
			"bytes-per-line must be between 1 and 256, got %d", cols)
	}
	return cols, nil
}

// writeHexRows writes comma-separated byte literals. When trailing is true,
// every row ends with a comma; otherwise only rows followed by more data do,
// which keeps PowerShell, Nim, and similar newline-continued lists valid.
func writeHexRows(b *strings.Builder, data []byte, cols int, indent, suffix string, trailing bool) {
	for i := 0; i < len(data); i += cols {
		end := i + cols
		if end > len(data) {
			end = len(data)
		}
		b.WriteString(indent)
		for j := i; j < end; j++ {
			if j > i {
				b.WriteString(", ")
			}
			fmt.Fprintf(b, "0x%02X%s", data[j], suffix)
		}
		if trailing || end < len(data) {
			b.WriteString(",")
		}
		b.WriteString("\n")
	}
}

// ---------------------------------------------------------------- C#

type csharpArrayRenderer struct{}

func (csharpArrayRenderer) Info() registry.Info {
	return registry.Info{
		Name:        "csharp-array",
		Description: "C# byte array (data declaration only)",
		Security:    registry.SecurityRenderer,
		Reversible:  true,
		Input:       "transformed bytes",
		Output:      "C# source text",
		Parameters:  []string{"--symbol NAME", "--bytes-per-line N"},
	}
}

func (csharpArrayRenderer) Render(data []byte, meta registry.Meta) ([]byte, error) {
	symbol, err := resolveSymbol(meta, "C#")
	if err != nil {
		return nil, err
	}
	cols, err := resolveCols(meta)
	if err != nil {
		return nil, err
	}

	var b strings.Builder
	writeLangHeader(&b, "// ", meta, data)
	if len(data) == 0 {
		fmt.Fprintf(&b, "byte[] %s = new byte[0]; // placeholder: input was empty\n", symbol)
		return []byte(b.String()), nil
	}
	fmt.Fprintf(&b, "byte[] %s = new byte[] {\n", symbol)
	writeHexRows(&b, data, cols, "    ", "", true)
	b.WriteString("};\n")
	return []byte(b.String()), nil
}

