func TestRenderWithKeySourceRenderers(t *testing.T) {
	data := []byte{0x00, 0x41, 0xFF}
	key := []byte{0x00, 0x11, 0x22, 0xFF}
	for _, name := range []string{
		"c-array", "csharp-array", "nim-array", "go-bytes", "python-bytes",
		"powershell-bytes", "vba-array", "vbs-array", "rust-array",
		"javascript-array", "zig-array",
	} {
		t.Run(name, func(t *testing.T) {
			if !KeyCapable(name) {
				t.Fatalf("%s is not key-capable", name)
			}
			m := meta("encrypt")
			m.Symbol = "payload"
			out, err := RenderWithKey(name, data, key, m, "key")
			if err != nil {
				t.Fatal(err)
			}
			s := string(out)
			if !strings.Contains(s, "payload") {
				t.Fatalf("missing data symbol:\n%s", s)
			}
			if !strings.Contains(s, "key") {
				t.Fatalf("missing key symbol:\n%s", s)
			}
			if strings.Count(s, "Generated by ByteForge") != 2 {
				t.Fatalf("expected data and key declarations:\n%s", s)
			}
			if name != "python-bytes" && strings.Count(s, "SHA-256") != 1 {
				t.Fatalf("key declaration should not contain a digest:\n%s", s)
			}
		})
	}
}

func TestRenderWithKeyJSON(t *testing.T) {
	data := []byte{0xDE, 0xAD}
	key := []byte{0x00, 0x11, 0x22, 0xFF}
	out, err := RenderWithKey("json", data, key, meta("encrypt"), "key")
	if err != nil {
		t.Fatal(err)
	}

	var doc struct {
		Data string `json:"data"`
		Key  struct {
			Symbol   string `json:"symbol"`
			Encoding string `json:"encoding"`
			Size     int    `json:"size"`
			Data     string `json:"data"`
		} `json:"key"`
	}
	if err := json.Unmarshal(out, &doc); err != nil {
		t.Fatalf("invalid JSON: %v\n%s", err, out)
	}
	if doc.Data != base64.StdEncoding.EncodeToString(data) {
		t.Fatalf("data = %q", doc.Data)
	}
	if doc.Key.Symbol != "key" || doc.Key.Encoding != "base64" || doc.Key.Size != len(key) {
		t.Fatalf("key = %+v", doc.Key)
	}
	if doc.Key.Data != base64.StdEncoding.EncodeToString(key) {
		t.Fatalf("key data = %q", doc.Key.Data)
	}
}

func TestRenderWithKeyRejectsBareRenderers(t *testing.T) {
	for _, name := range []string{"raw", "hex", "base64"} {
		if KeyCapable(name) {
			t.Fatalf("%s should not be key-capable", name)
		}
		_, err := RenderWithKey(name, []byte{1}, []byte{2}, meta("encrypt"), "key")
		if err == nil {
			t.Fatalf("%s accepted key material", name)
		}
		if bferrors.KindOf(err) != bferrors.Usage {
			t.Fatalf("%s error kind = %v", name, bferrors.KindOf(err))
		}
	}
}

func TestRenderWithKeyRejectsSymbolConflict(t *testing.T) {
	m := meta("encrypt")
	m.Symbol = "key"
	if _, err := RenderWithKey("go-bytes", []byte{1}, []byte{2}, m, "key"); err == nil {
		t.Fatal("accepted identical data and key symbols")
	}
}

func TestRenderWithKeyDefaultSymbol(t *testing.T) {
	out, err := RenderWithKey("go-bytes", []byte{1}, []byte{2}, meta("encrypt"), "")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(out), "var key = []byte{") {
		t.Fatalf("missing default key symbol:\n%s", out)
	}
}

func TestKeyCapableNamesSorted(t *testing.T) {
	names := KeyCapableNames()
	for i := 1; i < len(names); i++ {
		if names[i-1] >= names[i] {
			t.Fatalf("names not sorted: %v", names)
		}
	}
	if !KeyCapable("json") {
		t.Fatal("json should be key-capable")
	}
}
