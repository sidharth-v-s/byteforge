// ---------------------------------------------------------------- raw

type rawRenderer struct{}

func (rawRenderer) Info() registry.Info {
	return registry.Info{
		Name:        "raw",
		Description: "Exact binary bytes (no representation change)",
		Security:    registry.SecurityRenderer,
		Reversible:  true,
		Input:       "transformed bytes",
		Output:      "binary",
	}
}

func (rawRenderer) Render(data []byte, _ registry.Meta) ([]byte, error) {
	out := make([]byte, len(data))
	copy(out, data)
	return out, nil
}

// ---------------------------------------------------------------- hex text

type hexRenderer struct{}

func (hexRenderer) Info() registry.Info {
	return registry.Info{
		Name:        "hex",
		Description: "Uppercase hexadecimal text",
		Security:    registry.SecurityRenderer,
		Reversible:  true,
		Input:       "transformed bytes",
		Output:      "hex text",
	}
}

func (hexRenderer) Render(data []byte, _ registry.Meta) ([]byte, error) {
	if len(data) == 0 {
		return []byte{}, nil
	}
	out := make([]byte, hex.EncodedLen(len(data))+1)
	hex.Encode(out, data)
	for i := 0; i < len(out)-1; i++ {
		if out[i] >= 'a' && out[i] <= 'f' {
			out[i] -= 'a' - 'A'
		}
	}
	out[len(out)-1] = '\n'
	return out, nil
}

// ---------------------------------------------------------------- base64 text

type base64Renderer struct{}

func (base64Renderer) Info() registry.Info {
	return registry.Info{
		Name:        "base64",
		Description: "Standard Base64 text with padding",
		Security:    registry.SecurityRenderer,
		Reversible:  true,
		Input:       "transformed bytes",
		Output:      "Base64 text",
	}
}

func (base64Renderer) Render(data []byte, _ registry.Meta) ([]byte, error) {
	if len(data) == 0 {
		return []byte{}, nil
	}
	out := make([]byte, base64.StdEncoding.EncodedLen(len(data))+1)
	base64.StdEncoding.Encode(out, data)
	out[len(out)-1] = '\n'
	return out, nil
}

// ---------------------------------------------------------------- C array

var symbolPattern = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

type cArrayRenderer struct{}

func (cArrayRenderer) Info() registry.Info {
	return registry.Info{
		Name:        "c-array",
		Description: "C/C++ unsigned char array (data declaration only)",
		Security:    registry.SecurityRenderer,
		Reversible:  true,
		Input:       "transformed bytes",
		Output:      "C source text",
		Parameters:  []string{"--symbol NAME", "--bytes-per-line N"},
	}
}

func (cArrayRenderer) Render(data []byte, meta registry.Meta) ([]byte, error) {
	symbol := meta.Symbol
	if symbol == "" {
		symbol = "data"
	}
	if !symbolPattern.MatchString(symbol) {
		return nil, bferrors.New(bferrors.Usage,
			"invalid C symbol name %q: must match [A-Za-z_][A-Za-z0-9_]*", symbol)
	}
	cols := meta.BytesPerLine
	if cols == 0 {
		cols = 16
	}
	if cols < 1 || cols > 256 {
		return nil, bferrors.New(bferrors.Usage, "bytes-per-line must be between 1 and 256, got %d", cols)
	}

	sum := sha256.Sum256(data)
	var b strings.Builder
	fmt.Fprintf(&b, "/* Generated by ByteForge %s — data declaration only. */\n", version.Version)
	if meta.Operation != "" {
		fmt.Fprintf(&b, "/* Operation: %s", meta.Operation)
		if meta.Format != "" {
			fmt.Fprintf(&b, " | Format: %s", meta.Format)
		}
		fmt.Fprintf(&b, " | Bytes: %d | SHA-256: %s */\n", len(data), hex.EncodeToString(sum[:]))
	}

	if len(data) == 0 {
		fmt.Fprintf(&b, "unsigned char %s[] = { 0x00 }; /* placeholder: input was empty */\n", symbol)
		return []byte(b.String()), nil
	}

	fmt.Fprintf(&b, "unsigned char %s[] = {\n", symbol)
	for i := 0; i < len(data); i += cols {
		end := i + cols
		if end > len(data) {
			end = len(data)
		}
		b.WriteString("    ")
		for j := i; j < end; j++ {
			if j > i {
				b.WriteString(" ")
			}
			fmt.Fprintf(&b, "0x%02X,", data[j])
		}
		b.WriteString("\n")
	}
	b.WriteString("};\n")
	return []byte(b.String()), nil
}

// ---------------------------------------------------------------- Python bytes

type pythonBytesRenderer struct{}

func (pythonBytesRenderer) Info() registry.Info {
	return registry.Info{
		Name:        "python-bytes",
		Description: "Python bytes literal (data only)",
		Security:    registry.SecurityRenderer,
		Reversible:  true,
		Input:       "transformed bytes",
		Output:      "Python source text",
		Parameters:  []string{"--symbol NAME", "--bytes-per-line N"},
	}
}

func (pythonBytesRenderer) Render(data []byte, meta registry.Meta) ([]byte, error) {
	symbol := meta.Symbol
	if symbol == "" {
		symbol = "data"
	}
	if symbol == "_" {
		symbol = "data"
	} else if symbol != "" && !pythonIdentifier(symbol) {
		return nil, bferrors.New(bferrors.Usage, "invalid Python identifier %q", symbol)
	}
	cols := meta.BytesPerLine
	if cols == 0 {
		cols = 16
	}
	if cols < 1 || cols > 256 {
		return nil, bferrors.New(bferrors.Usage, "bytes-per-line must be between 1 and 256, got %d", cols)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by ByteForge %s — data literal only.\n", version.Version)
	if len(data) == 0 {
		fmt.Fprintf(&b, "%s = b\"\"\n", symbol)
		return []byte(b.String()), nil
	}
	fmt.Fprintf(&b, "%s = (\n", symbol)
	for i := 0; i < len(data); i += cols {
		end := i + cols
		if end > len(data) {
			end = len(data)
		}
		b.WriteString("    b\"")
		for _, by := range data[i:end] {
			fmt.Fprintf(&b, "\\x%02x", by)
		}
		b.WriteString("\"\n")
	}
	b.WriteString(")\n")
	return []byte(b.String()), nil
}

func pythonIdentifier(s string) bool {
	if s == "" {
		return false
	}
	for i, r := range s {
		if r == '_' || (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') {
			continue
		}
		if i > 0 && r >= '0' && r <= '9' {
			continue
		}
		return false
	}
	return true
}

// ---------------------------------------------------------------- JSON

type jsonDocument struct {
	SchemaVersion string           `json:"schemaVersion"`
	Tool          string           `json:"tool"`
	Version       string           `json:"version"`
	Timestamp     string           `json:"timestamp,omitempty"`
	Operation     string           `json:"operation,omitempty"`
	Format        string           `json:"format,omitempty"`
	Encoding      string           `json:"encoding,omitempty"`
	Cipher        string           `json:"cipher,omitempty"`
	InputSize     int              `json:"inputSize"`
	OutputSize    int              `json:"outputSize"`
	InputSHA256   string           `json:"inputSha256,omitempty"`
	OutputSHA256  string           `json:"outputSha256"`
	Verification  string           `json:"verification,omitempty"`
	DataEncoding  string           `json:"dataEncoding"`
	Data          string           `json:"data"`
	Key           *jsonKeyDocument `json:"key,omitempty"`
}

type jsonKeyDocument struct {
	Symbol   string `json:"symbol"`
	Encoding string `json:"encoding"`
	Size     int    `json:"size"`
	Data     string `json:"data"`
}

type jsonRenderer struct{}

func (jsonRenderer) Info() registry.Info {
	return registry.Info{
		Name:        "json",
		Description: "Structured JSON metadata with Base64-encoded data",
		Security:    registry.SecurityRenderer,
		Reversible:  true,
		Input:       "transformed bytes",
		Output:      "JSON text",
		Parameters:  []string{"schemaVersion 1.0", "data is Base64"},
	}
}

func (jsonRenderer) Render(data []byte, meta registry.Meta) ([]byte, error) {
	return jsonRenderer{}.render(data, meta, nil)
}

func (jsonRenderer) render(data []byte, meta registry.Meta, key *jsonKeyDocument) ([]byte, error) {
	sum := sha256.Sum256(data)
	doc := jsonDocument{
		SchemaVersion: "1.0",
		Tool:          "byteforge",
		Version:       version.Version,
		Timestamp:     meta.Timestamp,
		Operation:     meta.Operation,
		Format:        meta.Format,
		Encoding:      meta.Encoding,
		Cipher:        meta.Cipher,
		InputSize:     meta.InputSize,
		OutputSize:    len(data),
		InputSHA256:   meta.InputSHA256,
		OutputSHA256:  hex.EncodeToString(sum[:]),
		Verification:  strings.ToLower(meta.Verification),
		DataEncoding:  "base64",
		Data:          base64.StdEncoding.EncodeToString(data),
		Key:           key,
	}
	out, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return nil, bferrors.Wrap(bferrors.Processing, err, "encoding JSON output")
	}
	out = append(out, '\n')
	return out, nil
}
